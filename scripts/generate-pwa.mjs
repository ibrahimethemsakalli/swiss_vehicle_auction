import { readFile, writeFile, mkdir } from 'node:fs/promises';
import sharp from 'sharp';
const languages = ['de', 'fr', 'it', 'en'];
const dictionaries = Object.fromEntries(
  await Promise.all(
    languages.map(async (l) => [l, JSON.parse(await readFile(`src/messages/${l}.json`, 'utf8'))]),
  ),
);
const escape = (s) =>
  s.replace(
    /[&<>"']/g,
    (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c],
  );
const html = `<!doctype html><html lang="de"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="robots" content="noindex,nofollow"><title>AutoVeri.ch — Offline</title><style>
*{box-sizing:border-box}body{margin:0;background:#f1f5f9;color:#0f172a;font:18px/1.6 system-ui,sans-serif}main{max-width:640px;margin:5vh auto;padding:24px}h1{font-size:1.7rem;line-height:1.25}a{color:#0f172a;overflow-wrap:anywhere}section{display:none;background:white;padding:24px;border-radius:16px;margin-top:24px;overflow-wrap:anywhere}label{display:inline-block;padding:10px 6px;cursor:pointer}input{accent-color:#10b981}input:focus-visible+label,a:focus-visible{outline:3px solid #10b981;outline-offset:3px}.brand{font-weight:800;font-size:24px}.brand span{color:#10b981}.actions{display:flex;flex-wrap:wrap;gap:20px}.note{font-size:15px;color:#475569}
${languages.map((l) => `#${l}:checked~section[lang="${l}"]{display:block}`).join('\n')}
</style></head><body><main><div class="brand">AutoVeri<span>.ch</span></div>
${languages.map((l, i) => `<input type="radio" name="language" id="${l}" ${i === 0 ? 'checked' : ''}><label for="${l}">${l.toUpperCase()}</label>`).join('')}
${languages
  .map((l) => {
    const d = dictionaries[l];
    return `<section lang="${l}"><h1>${escape(d.pwaOfflineTitle)}</h1><p>${escape(d.pwaOfflineBody)}</p><p class="note">${escape(d.pwaPrivacy)}</p><p class="note">${escape(d.pwaNoPush)}</p><div class="actions"><a href="">${escape(d.pwaRetry)}</a><a href="/?lang=${l}">${escape(d.pwaHome)}</a></div></section>`;
  })
  .join('\n')}
</main></body></html>`;
const worker = `// Generated by scripts/generate-pwa.mjs. No runtime data or page cache.
const OFFLINE_HTML = ${JSON.stringify(html)};
self.addEventListener('activate', event => event.waitUntil(self.clients.claim()));
self.addEventListener('fetch', event => {
  const request = event.request, url = new URL(request.url);
  // Never intercept APIs, mutations, RSC/prefetch, images or cross-origin requests.
  if (request.method !== 'GET' || request.mode !== 'navigate' || url.origin !== self.location.origin || /^\\/(api|_next)(\\/|$)/.test(url.pathname)) return;
  event.respondWith(fetch(request, {cache:'no-store'}).catch(() => new Response(OFFLINE_HTML, {
    status:503, headers:{'Content-Type':'text/html; charset=utf-8','Cache-Control':'no-store','X-Robots-Tag':'noindex, nofollow',
    'Content-Security-Policy':"default-src 'none'; style-src 'unsafe-inline'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'"}
  })));
});
`;
const files = { 'public/offline.html': html, 'public/sw.js': worker };
if (process.argv.includes('--check')) {
  for (const [path, expected] of Object.entries(files))
    if ((await readFile(path, 'utf8')) !== expected)
      throw Error(`Regenerate ${path}: node scripts/generate-pwa.mjs`);
  console.log('PASS: PWA static assets match four-language source');
} else {
  for (const [path, content] of Object.entries(files)) await writeFile(path, content);
  await mkdir('public/pwa', { recursive: true });
  // Repo-native brand mark; no third-party image or licence needed.
  const svg = Buffer.from(
    '<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512"><rect width="512" height="512" fill="#0F172A"/><path d="M152 360 238 152h50l84 208h-60l-16-45h-77l-17 45zm84-94h43l-21-64z" fill="white"/><circle cx="352" cy="354" r="25" fill="#10B981"/></svg>',
  );
  for (const size of [192, 512])
    await sharp(svg).resize(size, size).removeAlpha().png().toFile(`public/pwa/icon-${size}.png`);
  await sharp(svg).removeAlpha().png().toFile('public/pwa/maskable-512.png');
  console.log('Generated static offline screen, service worker and brand icons.');
}
